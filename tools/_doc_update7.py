# -*- coding: utf-8 -*-
"""一次性脚本：把 1.3.2（中局/残局连线修复）写进更新日志。"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "1.3.2（2026-09-26）"
LINES = [
    "",
    "============================================================",
    "1.3.2（2026-09-26）：修复「中局/残局连线同步不上」",
    "============================================================",
    "",
    "  问题：自己走几步再连线（中局 / 残局接入）时，只能识别出棋子个数，",
    "        局面同步不上、也看不到具体位置。",
    "",
    "  原因：中局/残局接入靠「接管对方当前局面」这条路（两边差得太多时，",
    "        就把对方局面设成我们自己的局面）。接管成功以后，朝向判断又被",
    "        「按我方执黑推断」的默认值覆盖回去了 —— 于是每一帧的坐标换算",
    "        和接管时用的不是同一套，「两次识别之间的差异」永远算不出一步棋，",
    "        同步就一直失败。",
    "",
    "  修复：",
    "    · 朝向一旦定下来（尤其是已经接管 / 同步过局面之后）就锁定，",
    "      不再每帧按执黑默认值推翻；",
    "    · 只有「还没同步过任何一步」时，才允许用棋子证据纠正朝向",
    "      （例如连的就是同一盘棋的中局，证据非常明确）；",
    "    · 手动指定的朝向始终优先。",
    "",
    "  新增回归用例（真实 YOLO 识别 + 模拟对方窗口画面）：",
    "    · 本地在开局、对方已经是中局（12 手）→ 必须接管过来（含 180° 视角）；",
    "    · 残局（只剩 4 个子）→ 必须接管过来；",
    "    · 接管之后对方再走一步 → 必须继续同步；",
    "    · 接管后朝向不能再被改回去（就是这次坏掉的那点）。",
    "",
]


def main() -> int:
    path = ROOT / "更新日志.txt"
    text = path.read_text(encoding="utf-8")
    if MARK in text:
        print("更新日志：已有 1.3.2 条目")
        return 0
    lines = text.split("\n")
    for position, line in enumerate(lines):
        if line.startswith("二、"):
            lines.insert(position, "\n".join(LINES).strip("\n") + "\n")
            break
    else:
        lines.append("\n".join(LINES))
    path.write_text("\n".join(lines), encoding="utf-8")
    print("更新日志：已插入 1.3.2 条目")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
